"""Build the credited c3f3ac25 source ancestor from coefficients, not a circuit."""
from pathlib import Path
import argparse,hashlib,json,os,sys,time

def sha(path):
    with path.open('rb') as f:return hashlib.file_digest(f,'sha256').hexdigest()

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('output',type=Path);p.add_argument('--data',type=Path,required=True);p.add_argument('--runtime',type=Path,required=True)
    p.add_argument('--retire',type=int,default=3);p.add_argument('--prefix',type=int,default=0)
    p.add_argument('--experimental',action='store_true',help='Explicitly build an unverified architecture variant, not the pinned ancestor')
    a=p.parse_args();out=a.output.resolve()
    if out.exists():raise FileExistsError(out)
    if (a.retire,a.prefix)!=(3,0) and not a.experimental:p.error('Architecture changes require --experimental')
    root=Path(__file__).resolve().parents[1];source=root/'vendor/invsqrt_source'
    os.environ.update(OPENBLAS_NUM_THREADS='1',OMP_NUM_THREADS='1',MKL_NUM_THREADS='1',CUDA_VISIBLE_DEVICES='')
    sys.dont_write_bytecode=True
    sys.path[:0]=[str(a.runtime.resolve()),str((a.data/'verifiers').resolve()),str(source)]
    out.mkdir(parents=True);opened=[]
    def audit(event,args):
        if event=='open' and isinstance(args[0],(str,bytes,os.PathLike)):
            path=Path(os.fsdecode(args[0])).resolve()
            if path.suffix in ('.kmb','.kmx') and not path.is_relative_to(out):raise RuntimeError('External compiled input forbidden')
            if path.is_relative_to(source) or path.is_relative_to(out):opened.append(str(path))
    sys.addaudithook(audit)
    import round10_inv as gen
    gen.setup(a.data.resolve())
    # The upstream setup adds data/kickmix; honor the explicit runtime choice.
    sys.path.insert(0,str(a.runtime.resolve()))
    import round10_lookup as unary
    from round11_lookup import lookup as davio
    unary.lookup=davio
    recipe=json.loads((source/'selected_invsqrt.json').read_text())
    start=time.perf_counter()
    model=gen.build_model(out/'model',fit_file=source/'selected_phase_fit.json',recipe=recipe['recipe'])
    options={**recipe['options'],'retire':a.retire,'prefix':a.prefix}
    circuit,stats=gen.build_variant(out/'build',model,**options);del circuit
    path=gen.optimize(out/'build')
    import kickmix as km
    native_path=Path(km.__file__).resolve()
    assert native_path.is_relative_to(a.runtime.resolve()),'Native module differs from --runtime'
    c=km.Circuit.from_file(str(path),format='kmb')
    target=out/'invsqrt.kmb'
    # Preserve the original generated bytes instead of reserializing.
    import shutil
    shutil.copy2(path,target)
    digest=sha(target)
    if not a.experimental:assert digest==recipe['sha256']
    modules={str(Path(m.__file__).resolve().relative_to(source)):sha(Path(m.__file__).resolve()) for m in list(sys.modules.values()) if getattr(m,'__file__',None) and Path(m.__file__).resolve().is_relative_to(source)}
    report={'status':'SOURCE_GENERATED_EXPERIMENTAL' if a.experimental else 'EXACT_SOURCE_ANCESTOR_REBUILT','sha256':digest,'expected_ancestor_sha256':recipe['sha256'],'source_sha256':modules,'constructor_sha256':sha(Path(__file__)),'native_module_sha256':sha(native_path),'native_module_path':str(native_path),'numeric_recipe_sha256':sha(source/'selected_invsqrt.json'),'phase_recipe_sha256':sha(source/'selected_phase_fit.json'),'options':options,'qubits':c.num_qubits,'static_toffoli':c.operation_statistics().num_toffoli_like,'preoptimization_probe':stats,'workspace_files_opened':sorted(set(opened)),'seconds':time.perf_counter()-start,'native_full_verification_performed':False}
    (out/'source-build.json').write_text(json.dumps(report,indent=2),encoding='utf-8')
    print(json.dumps({k:v for k,v in report.items() if k not in ('source_sha256','workspace_files_opened','preoptimization_probe')}),flush=True)

if __name__=='__main__':main()
